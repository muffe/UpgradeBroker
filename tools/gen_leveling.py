# Writes Data/Leveling.lua from WoW Forever game tables (CSV exports from https://wago.tools/db2/<Table>/csv?build=...).
# Usage: python3 tools/gen_leveling.py <folder with the CSVs> Data/Leveling.lua
import csv, os, sys
d = sys.argv[1]; out = sys.argv[2]
def load(t):
    with open(os.path.join(d, t), newline='', encoding='utf-8') as f: return list(csv.DictReader(f))
es = [r for r in load('es_1.60.1.71037.csv') if r['ContentSetID'] == '0' and r['ExpansionID'] == '-2']
es = {int(r['Lvl']): r for r in es}
names = {r['ID']: r['Name_lang'] for r in load('f_SpellName.csv')}
lv = {r['SpellID']: r for r in load('f_SpellLevels.csv') if r['DifficultyID'] == '0'}
misc = {r['SpellID']: r for r in load('f_SpellMisc.csv')}
ct = {r['ID']: int(r['Base']) for r in load('f_SpellCastTimes.csv')}
pw = {r['SpellID']: r for r in load('f_SpellPower.csv')}
fe = {}
for r in load('f_SpellEffect.csv'):
    if r['Effect'] in ('2', '10') and r['SpellID'] not in fe: fe[r['SpellID']] = r
def rank(name, lvl):
    best = None
    for sid, nm in names.items():
        if nm != name or sid not in lv or sid not in pw or sid not in fe: continue
        L = lv[sid]; sl = int(L['SpellLevel']); bl = int(L['BaseLevel']); ml = int(L['MaxLevel'])
        if bl == 0 or sl > lvl or int(pw[sid]['ManaCost'] or 0) <= 0: continue
        if best is None or sl > best[0]: best = (sl, sid, bl, ml)
    if not best: return None
    sl, sid, bl, ml = best
    k = (min(lvl, ml) if ml else lvl) - bl
    f = fe[sid]
    avg = float(f['EffectBasePointsF']) + float(f['EffectRealPointsPerLevel']) * max(0, k)
    cast = max(1.5, ct[misc[sid]['CastingTimeIndex']] / 1000)
    return (round(avg), int(pw[sid]['ManaCost']), cast, round(float(f['EffectBonusCoefficient']), 3), sid)
SPELLS = ['Shadow Bolt', 'Frostbolt', 'Fireball', 'Smite', 'Lightning Bolt', 'Wrath', 'Holy Light', 'Healing Wave', 'Healing Touch', 'Lesser Heal', 'Heal', 'Greater Heal']
L = []
L.append('-- Data/Leveling.lua: GENERATED by ref/forever-data/scripts/gen_leveling.py from WoW Forever game tables')
L.append('-- (wago.tools, build 1.60.1.71037, 2026-11-20). Do not edit by hand.')
L.append('local _, GL = ...')
L.append('local D = {}')
L.append('GL.LevelingData = D')
L.append('-- ExpectedStat (normal creatures): health, auto-attack DPS before armor, armor, armor constant (400 + 85 x level)')
L.append('D.creature = {')
for lvl in range(1, 61):
    r = es[lvl]
    L.append('\t[%d] = { %s, %.2f, %s, %s },' % (lvl, r['CreatureHealth'], float(r['CreatureAutoAttackDps']), r['CreatureArmor'], r['ArmorConstant']))
L.append('}')
L.append('-- Highest rank known at each level: { average base amount, mana, cast seconds, spell power coefficient }')
L.append('D.spells = {')
for name in SPELLS:
    L.append('\t["%s"] = {' % name)
    for lvl in range(1, 61):
        x = rank(name, lvl)
        if x: L.append('\t\t[%d] = { %d, %d, %.2f, %.3f }, -- %s' % (lvl, x[0], x[1], x[2], x[3], x[4]))
    L.append('\t},')
L.append('}')
# Food and drink by required level (spell auras 84/85; amount per 5 s): restored per second
L.append('-- Vendor food and water by required level: health / mana per second while eating or drinking')
L.append('D.food = { { 1, 3.4 }, { 5, 11.6 }, { 15, 23.0 }, { 25, 32.4 }, { 35, 46.4 }, { 45, 71.6 }, { 55, 106 } }')
L.append('D.drink = { { 1, 8.4 }, { 5, 20.8 }, { 15, 34.8 }, { 25, 49.8 }, { 35, 66.4 }, { 45, 97.8 }, { 55, 140 } }')
open(out, 'w').write('\n'.join(L) + '\n')
