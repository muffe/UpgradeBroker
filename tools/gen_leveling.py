# Writes Data/Leveling.lua from WoW Forever game tables (CSV exports from https://wago.tools/db2/<Table>/csv?build=...).
# Usage: python3 tools/gen_leveling.py <folder with the CSVs> Data/Leveling.lua
import csv, os, sys
d = sys.argv[1]; out = sys.argv[2]
def load(t):
    with open(os.path.join(d, t), newline='', encoding='utf-8') as f: return list(csv.DictReader(f))
es = [r for r in load('ExpectedStat.csv') if r['ContentSetID'] == '0' and r['ExpansionID'] == '-2']
es = {int(r['Lvl']): r for r in es}
names = {r['ID']: r['Name_lang'] for r in load('f_SpellName.csv')}
lv = {r['SpellID']: r for r in load('f_SpellLevels.csv') if r['DifficultyID'] == '0'}
misc = {r['SpellID']: r for r in load('f_SpellMisc.csv')}
ct = {r['ID']: int(r['Base']) for r in load('f_SpellCastTimes.csv')}
dur = {r['ID']: int(r['Duration']) for r in load('f_SpellDuration.csv')}
pw = {r['SpellID']: r for r in load('f_SpellPower.csv')}
fe, pe = {}, {}
for r in load('f_SpellEffect.csv'):
    if r['Effect'] in ('2', '10') and r['SpellID'] not in fe: fe[r['SpellID']] = r
    # periodic damage or leech (aura 3, 53) of a damage over time spell or a channel
    if r['Effect'] == '6' and r['EffectAura'] in ('3', '53') and r['SpellID'] not in pe: pe[r['SpellID']] = r
def best_rank(name, lvl, has):
    best = None
    for sid, nm in names.items():
        if nm != name or sid not in lv or sid not in pw or not has(sid): continue
        L = lv[sid]; sl = int(L['SpellLevel']); bl = int(L['BaseLevel']); ml = int(L['MaxLevel'])
        if bl == 0 or sl > lvl or int(pw[sid]['ManaCost'] or 0) <= 0: continue
        if best is None or sl > best[0]: best = (sl, sid, bl, ml)
    return best
def periodic(sid):
    # the whole damage over time: ticks x average tick, and its spell power coefficient
    f = pe[sid]
    d = dur[misc[sid]['DurationIndex']]
    ticks = d // int(f['EffectAuraPeriod'])
    return float(f['EffectBasePointsF']) * ticks, float(f['EffectBonusCoefficient']) * ticks, d / 1000
SCHOOL = {2: 'HOLY', 4: 'FIRE', 8: 'NATURE', 16: 'FROST', 32: 'SHADOW', 64: 'ARCANE'}
# channels count as one cast of their whole damage over the channel's time
CHANNELS = ['Mind Flay']
def channel(name, lvl):
    b = best_rank(name, lvl, lambda sid: sid in pe)
    if not b: return None
    sid = b[1]
    total, coef, d = periodic(sid)
    return (round(total), int(pw[sid]['ManaCost']), d, round(coef, 3), sid)
def dot(name, lvl):
    b = best_rank(name, lvl, lambda sid: sid in pe)
    if not b: return None
    sl, sid, bl, ml = b
    direct, dcoef = 0, 0
    if sid in fe:
        f = fe[sid]
        k = (min(lvl, ml) if ml else lvl) - bl
        direct = float(f['EffectBasePointsF']) + float(f['EffectRealPointsPerLevel']) * max(0, k)
        dcoef = float(f['EffectBonusCoefficient'])
    total, coef, d = periodic(sid)
    cast = ct[misc[sid]['CastingTimeIndex']] / 1000
    return (round(direct), round(dcoef, 3), round(total), round(coef, 3), d, int(pw[sid]['ManaCost']), cast, sid)
def rank(name, lvl):
    if name in CHANNELS: return channel(name, lvl)
    best = None
    for sid, nm in names.items():
        if nm != name or sid not in lv or sid not in pw or sid not in fe: continue
        L = lv[sid]; sl = int(L['SpellLevel']); bl = int(L['BaseLevel']); ml = int(L['MaxLevel'])
        if bl == 0 or sl > lvl or int(pw[sid]['ManaCost'] or 0) <= 0: continue
        if best is None or sl > best[0]: best = (sl, sid, bl, ml)
    if not best: return None
    sl, sid, bl, ml = best
    k = (min(lvl, ml) if ml else lvl) - bl
    f = fe[sid]
    avg = float(f['EffectBasePointsF']) + float(f['EffectRealPointsPerLevel']) * max(0, k)
    cast = max(1.5, ct[misc[sid]['CastingTimeIndex']] / 1000)
    return (round(avg), int(pw[sid]['ManaCost']), cast, round(float(f['EffectBonusCoefficient']), 3), sid)
SPELLS = ['Mind Flay', 'Shadow Bolt', 'Frostbolt', 'Fireball', 'Smite', 'Searing Pain', 'Arcane Wrath', 'Lightning Bolt', 'Wrath', 'Holy Light', 'Healing Wave', 'Healing Touch', 'Lesser Heal', 'Heal', 'Greater Heal']
L = []
L.append('-- Data/Leveling.lua: GENERATED by tools/gen_leveling.py from WoW Forever game tables')
L.append('-- (wago.tools, build 1.60.1.71139, 2026-11-25). Do not edit by hand.')
L.append('local _, GL = ...')
L.append('local D = {}')
L.append('GL.LevelingData = D')
L.append('-- ExpectedStat (normal creatures): health, auto-attack DPS before armor, armor, armor constant (400 + 85 x level)')
L.append('D.creature = {')
for lvl in range(1, 61):
    r = es[lvl]
    L.append('\t[%d] = { %s, %.2f, %s, %s },' % (lvl, r['CreatureHealth'], float(r['CreatureAutoAttackDps']), r['CreatureArmor'], r['ArmorConstant']))
L.append('}')
L.append('-- Highest rank known at each level: { average base amount, mana, cast seconds, spell power coefficient }')
L.append('D.spells = {')
for name in SPELLS:
    L.append('\t["%s"] = {' % name)
    for lvl in range(1, 61):
        x = rank(name, lvl)
        if x: L.append('\t\t[%d] = { %d, %d, %.2f, %.3f }, -- %s' % (lvl, x[0], x[1], x[2], x[3], x[4]))
    L.append('\t},')
L.append('}')
DOTS = ['Corruption', 'Bane of Agony', 'Immolate', 'Siphon Life', 'Shadow Word: Pain', 'Moonfire', 'Flame Shock']
L.append('-- Damage over time, highest rank at each level: { direct amount, its coefficient, all ticks together, their')
L.append('-- coefficient together, duration, mana, cast seconds }')
L.append('D.dots = {')
for name in DOTS:
    sid0 = next(sid for sid, nm in names.items() if nm == name and sid in pe and sid in misc)
    L.append('\t["%s"] = { school = "%s",' % (name, SCHOOL[int(misc[sid0]['SchoolMask'])]))
    for lvl in range(1, 61):
        x = dot(name, lvl)
        if x: L.append('\t\t[%d] = { %d, %.3f, %d, %.3f, %g, %d, %g }, -- %s' % (lvl, *x))
    L.append('\t},')
L.append('}')
# Food and drink by required level (spell auras 84/85; amount per 5 s): restored per second
L.append('-- Vendor food and water by required level: health / mana per second while eating or drinking')
L.append('D.food = { { 1, 3.4 }, { 5, 11.6 }, { 15, 23.0 }, { 25, 32.4 }, { 35, 46.4 }, { 45, 71.6 }, { 55, 106 } }')
L.append('D.drink = { { 1, 8.4 }, { 5, 20.8 }, { 15, 34.8 }, { 25, 49.8 }, { 35, 66.4 }, { 45, 97.8 }, { 55, 140 } }')
open(out, 'w').write('\n'.join(L) + '\n')
